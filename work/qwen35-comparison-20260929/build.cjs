const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const crypto = require('crypto');
const source = 'outputs/题干措辞与病例事实修复-20260929/01-出题子应用-题干措辞与病例事实修复版.json';
const dir = 'outputs/Qwen3.5Plus对照试跑-20260929';
const destination = path.join(dir, '01-出题子应用-Qwen3.5Plus对照版.json');
const original = JSON.parse(fs.readFileSync(source, 'utf8'));
const workflow = structuredClone(original);
const targets = ['sR35QbYF2xamDQR3', 'v12RevisionGenerator'];
const changes = targets.map(id => {
  const node = workflow.nodes.find(n => n.nodeId === id);
  assert(node, id);
  const input = key => node.inputs.find(i => i.key === key);
  assert.equal(input('model').value, 'qwen3.8-flash');
  assert.equal(input('aiChatReasoning').value, false);
  assert.equal(input('aiChatResponseFormat').value, 'json_object');
  assert.equal(input('maxToken').value, 16000);
  input('model').value = 'qwen3.5-plus';
  return {nodeId:id, name:node.name, field:'model', from:'qwen3.8-flash', to:'qwen3.5-plus', temperature:input('temperature').value, maxToken:input('maxToken').value, aiChatReasoning:false, responseFormat:'json_object'};
});
// Reversing the two intended field edits must recover the entire original export.
const reverted = structuredClone(workflow);
for (const id of targets) reverted.nodes.find(n=>n.nodeId===id).inputs.find(i=>i.key==='model').value='qwen3.8-flash';
assert.deepEqual(reverted, original);
assert.equal(workflow.nodes.length, 33);
assert.equal(workflow.edges.length, 52);
assert(!workflow.nodes.some(n=>n.inputs?.some(i=>i.key==='model' && i.value==='qwen3.8-flash')));
const kb = workflow.nodes.find(n=>n.nodeId==='wP0lzgeUtpvzxSHw');
assert(kb && kb.name==='知识库搜索');
assert.deepEqual(kb.inputs.find(i=>i.key==='datasets').value, []);
fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(destination, JSON.stringify(workflow,null,2)+'\n');
assert.deepEqual(JSON.parse(fs.readFileSync(destination,'utf8')),workflow);
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const report = {source, destination, source_sha256:hash(source), destination_sha256:hash(destination), changes, node_count:33, edge_count:52, verification:'JSON解析、两处模型字段变更及其他字段完全一致检查通过', online_run:false, kb_selection_required:true};
fs.writeFileSync(path.join(dir,'修改核对.json'),JSON.stringify(report,null,2)+'\n');
